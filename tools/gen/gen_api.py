def parse_file(path):
    text = strip_versions(open(path).read())
    for m in re.finditer(r'#define (arginfo_\w+) (arginfo_\w+)', text):
        aliases[m.group(1)] = m.group(2)
    for m in re.finditer(r'(ZEND_BEGIN_ARG_\w+)\((.*?)\)\n(.*?)ZEND_END_ARG_INFO\(\)', text, re.S):
        macro, head, body = m.group(1), args_split(m.group(2)), m.group(3)
        name = head[0]
        if macro == 'ZEND_BEGIN_ARG_INFO_EX':
            req, ret = head[3], ('null()', flags(head[2]))
        elif macro == 'ZEND_BEGIN_ARG_WITH_RETURN_TYPE_INFO_EX':
            req, ret = head[2], ('null()', code_mask(head[3], head[4]) | flags(head[1]))
        elif macro == 'ZEND_BEGIN_ARG_WITH_TENTATIVE_RETURN_TYPE_INFO_EX':
            req, ret = head[2], ('null()', code_mask(head[3], head[4]) | flags(head[1], 0, 1))
        elif macro == 'ZEND_BEGIN_ARG_WITH_RETURN_OBJ_INFO_EX':
            req, ret = head[2], (rstr(head[3]), TYPE_LITERAL_NAME_BIT | (NULLABLE_BIT if head[4] == '1' else 0) | flags(head[1]))
        elif macro == 'ZEND_BEGIN_ARG_WITH_RETURN_TYPE_MASK_EX':
            req, ret = head[2], ('null()', mask_expr(head[3]) | flags(head[1]))
        elif macro == 'ZEND_BEGIN_ARG_WITH_RETURN_OBJ_TYPE_MASK_EX':
            req, ret = head[2], (rstr(head[3]), TYPE_LITERAL_NAME_BIT | mask_expr(head[4]) | flags(head[1]))
        else:
            raise Exception(macro)
        rows = [('%s as *const c_char' % ('%susize' % req), ret[0], ret[1], 'null()')]
        for a in re.finditer(r'(ZEND_ARG_\w+)\((.*)\)', body):
            am, aa = a.group(1), args_split(a.group(2))
            dflt = 'null()'
            if am == 'ZEND_ARG_TYPE_INFO':
                row = (rstr(aa[1]), 'null()', code_mask(aa[2], aa[3]) | flags(aa[0]))
            elif am == 'ZEND_ARG_TYPE_INFO_WITH_DEFAULT_VALUE':
                row = (rstr(aa[1]), 'null()', code_mask(aa[2], aa[3]) | flags(aa[0])); dflt = 'c' + aa[4]
            elif am == 'ZEND_ARG_OBJ_INFO':
                row = (rstr(aa[1]), rstr(aa[2]), TYPE_LITERAL_NAME_BIT | (NULLABLE_BIT if aa[3] == '1' else 0) | flags(aa[0]))
            elif am == 'ZEND_ARG_OBJ_INFO_WITH_DEFAULT_VALUE':
                row = (rstr(aa[1]), rstr(aa[2]), TYPE_LITERAL_NAME_BIT | (NULLABLE_BIT if aa[3] == '1' else 0) | flags(aa[0])); dflt = 'c' + aa[4]
            elif am == 'ZEND_ARG_TYPE_MASK':
                row = (rstr(aa[1]), 'null()', mask_expr(aa[2]) | flags(aa[0]))
                if aa[3] != 'NULL':
                    dflt = 'c' + aa[3]
            elif am == 'ZEND_ARG_OBJ_TYPE_MASK':
                row = (rstr(aa[1]), rstr(aa[2]), TYPE_LITERAL_NAME_BIT | mask_expr(aa[3]) | flags(aa[0]))
                if aa[4] != 'NULL':
                    dflt = 'c' + aa[4]
            elif am in ('ZEND_ARG_VARIADIC_TYPE_INFO',):
                row = (rstr(aa[1]), 'null()', code_mask(aa[2], aa[3]) | flags(aa[0], 1))
            elif am in ('ZEND_ARG_INFO',):
                row = (rstr(aa[1]), 'null()', flags(aa[0]))
            else:
                raise Exception(am)
            rows.append(row + (dflt,))
        arginfos[name] = rows
    for m in re.finditer(r'static const zend_function_entry (\w+)\[\] = \{(.*?)\};', text, re.S):
        entries = []
        for e in re.finditer(r'(ZEND_ME|ZEND_RAW_FENTRY|ZEND_ABSTRACT_ME_WITH_FLAGS)\((.*)\)', m.group(2)):
            em, ea = e.group(1), args_split(e.group(2))
            if em == 'ZEND_ME':
                h = 'zim_%s_%s' % (ea[0], ea[1])
                entries.append((rstr(ea[1]), h, ea[2], ea[3]))
            elif em == 'ZEND_ABSTRACT_ME_WITH_FLAGS':
                entries.append((rstr(ea[1]), None, ea[2], ea[3]))
            else:
                nm = re.match(r'ZEND_NS_NAME\("(.*)", "(.*)"\)', ea[0])
                fname = rstr('%s\\\\%s' % (nm.group(1), nm.group(2))) if nm else rstr(ea[0].strip('"'))
                entries.append((fname, ea[1], ea[2], ea[3]))
            if entries[-1][1]:
                handlers.append(entries[-1][1])
        tables[m.group(1)] = entries
    for m in re.finditer(r'static zend_class_entry \*(register_class_\w+)\((.*?)\)\n\{(.*?)\n\}', text, re.S):
        body = m.group(3)
        c = {'deps': [a.split('class_entry_', 1)[1] for a in args_split(m.group(2)) if 'class_entry_' in a]}
        ns = re.search(r'INIT_NS_CLASS_ENTRY\(ce, "(.*?)", "(.*?)", (\w+)\)', body)
        if ns:
            c['name'] = cname(ns.group(1) + '\\\\' + ns.group(2)); c['methods'] = ns.group(3)
        else:
            nc = re.search(r'INIT_CLASS_ENTRY\(ce, "(.*?)", (\w+)\)', body)
            if nc:
                c['name'] = cname(nc.group(1)); c['methods'] = nc.group(2)
        reg = re.search(r'zend_register_internal_class_with_flags\(&ce, (\w+), (.*?)\);', body)
        if reg:
            c['kind'] = 'class'
            c['parent'] = None if reg.group(1) == 'NULL' else reg.group(1).split('class_entry_', 1)[1]
            c['flags'] = reg.group(2)
        elif 'zend_register_internal_interface' in body:
            c['kind'] = 'interface'
        elif 'zend_register_internal_enum' in body:
            e = re.search(r'zend_register_internal_enum\("(.*?)", (\w+), (\w+)\)', body)
            c['kind'] = 'enum'; c['name'] = cname(e.group(1)); c['backing'] = e.group(2); c['methods'] = e.group(3)
            c['cases'] = re.findall(r'zend_enum_add_case_cstr\(class_entry, "(\w+)", NULL\)', body)
        else:
            raise Exception('unknown class kind in ' + m.group(1))
        imp = re.search(r'zend_class_implements\(class_entry, \d+, (.*?)\);', body)
        c['implements'] = [x.split('class_entry_', 1)[1] for x in args_split(imp.group(1))] if imp else []
        classes[m.group(1)] = c

