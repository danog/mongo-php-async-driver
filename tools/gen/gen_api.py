def ce_ref(dep):
    if dep in BUILTIN:
        return 'crate::zend::class::lookup(c"%s")' % BUILTIN[dep]
    return 'crate::zend::class::lookup(c"%s")' % dep.replace('_', '\\\\').lower()

def prop_type(t):
    """Reflection type string -> (class name or None, mask)"""
    if t is None:
        return None, 0  # untyped
    nullable = t.startswith('?')
    t = t.lstrip('?')
    m, cls = NULLABLE_BIT if nullable else 0, None
    names = {'int': 'MAY_BE_LONG', 'string': 'MAY_BE_STRING', 'bool': 'MAY_BE_BOOL', 'float': 'MAY_BE_DOUBLE',
             'array': 'MAY_BE_ARRAY', 'object': 'MAY_BE_OBJECT', 'mixed': 'MAY_BE_ANY', 'null': 'MAY_BE_NULL'}
    for p in t.split('|'):
        if p in names:
            m |= sysconst(names[p])
        else:
            cls = p
    return cls, m

