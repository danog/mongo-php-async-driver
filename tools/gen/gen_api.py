        src = open(p).read()
        for m in re.finditer(r'pub (?:unsafe )?(?:extern "C" )?fn ((?:zim|zif)_\w+|init_MongoDB_\w+)\(', src):
            impl[m.group(1)] = mod
        # handlers defined by macro invocations (e.g. unit_class!(..., zim_X_y, ...)) in the same module
        for m in re.finditer(r'^\w+!\((.*?)\);$', src, re.M | re.S):
            for n in re.findall(r'\b((?:zim|zif)_\w+|init_MongoDB_\w+)\b', m.group(1)):
                impl[n] = mod
