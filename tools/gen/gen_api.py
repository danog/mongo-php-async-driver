def sysconst(name):
    if name == '_IS_BOOL':
        return 18  # zend_types.h, not exported by bindgen (leading underscore)
    return ZEND_CONSTS[name]

TYPE_NAME_BIT = 1 << 24
TYPE_LITERAL_NAME_BIT = 1 << 23
TYPE_ITERABLE_BIT = 1 << 21
NULLABLE_BIT = 0x2
SEND_MODE_SHIFT = 25
IS_VARIADIC_BIT = 1 << (25 + 2)
IS_TENTATIVE_BIT = 1 << (25 + 4)

def mask_expr(s):
    """MAY_BE_LONG|MAY_BE_STRING -> int"""
    v = 0
    for part in s.split('|'):
        part = part.strip()
        if part in ('0', ''):
            continue
        v |= sysconst(part)
    return v

def code_mask(code, allow_null):
    c = sysconst(code)
    if code == '_IS_BOOL':
        m = sysconst('MAY_BE_BOOL')
    elif code == 'IS_ITERABLE':
        m = TYPE_ITERABLE_BIT
    elif code == 'IS_MIXED':
        m = sysconst('MAY_BE_ANY')
    else:
        m = 1 << c
    return m | (NULLABLE_BIT if allow_null == '1' else 0)

def flags(by_ref, variadic=0, tentative=0):
    return (int(by_ref) << SEND_MODE_SHIFT) | (IS_VARIADIC_BIT if variadic else 0) | (IS_TENTATIVE_BIT if tentative else 0)

def rstr(s):
    """C string literal body (already escaped as in C) -> Rust c"..." literal (C octal escapes,
    used by gen_stub.php for \\U..., become plain characters)"""
    out, i = '', 0
    while i < len(s):
        if s[i] == '\\' and i + 1 < len(s) and s[i + 1] in '01234567':
            j = i + 1
            while j < len(s) and j < i + 4 and s[j] in '01234567':
                j += 1
            out += chr(int(s[i + 1:j], 8)); i = j
        elif s[i] == '\\':
            out += s[i:i + 2]; i += 2
        else:
            out += s[i]; i += 1
    return 'c"%s"' % out

def cname(cls):
    """MongoDB\\\\BSON\\\\Int64 as written in the C macro -> MongoDB\\BSON\\Int64"""
    return cls.replace('\\\\', '\\')

def args_split(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

def strip_versions(text):
    """Keeps the PHP_VERSION_ID >= 80400 branches."""
    out, stack = [], []
    for line in text.split('\n'):
        t = line.strip()
        if t.startswith('#if'):
            stack.append('>= 80400' in t or 'PHP_VERSION_ID' not in t)
            continue
        if t.startswith('#else'):
            stack[-1] = not stack[-1]
            continue
        if t.startswith('#endif'):
            stack.pop()
            continue
        if all(stack):
            out.append(line)
    return '\n'.join(out)

