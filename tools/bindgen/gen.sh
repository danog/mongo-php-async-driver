#!/bin/sh
# Regenerates src/zend/sys/php<ver>.rs from the PHP headers of $PHP_CONFIG (NTS builds).
# Run on a host with the PHP headers and bindgen-cli + libclang; the output is checked in.
set -e
: "${PHP_CONFIG:?set PHP_CONFIG}"
inc=$($PHP_CONFIG --includes)
api=$($PHP_CONFIG --phpapi)
ver=$($PHP_CONFIG --version | cut -d. -f1,2 | tr -d .)
out="$(dirname "$0")/../../src/zend/sys/php$ver.rs"
bindgen "$(dirname "$0")/wrapper.h" -o "$out" \
  --allowlist-function '(zend|_zend|php|_php|zval|_zval|smart_str|_smart_str|object|_object|spl|_safe|_e|_estr|_ecalloc|_efree|_emalloc|_erealloc|gc|_gc|rc_|_try|display|cfg|sapi|ap_php|instanceof|add|convert|is_|_is|get_active|get_zval|ex_|compare|string_|numeric|increment|decrement|_zend_|zif|zim|module|OnUpdate|date_|timelib|_try_convert).*' \
  --allowlist-type '(zend|_zend|php|_php|zval|_zval|smart_str|sapi|timelib).*' \
  --allowlist-var '(zend|php|executor_globals|compiler_globals|core_globals|sapi_|module_registry|std_object_handlers|spl_ce|date_ce|php_json|json_globals|basic_globals|file_globals|ZEND|IS_|GC_|ZEND_|PHP_|E_|HASH_|ZSTR_|PHP_JSON|MAY_BE).*' \
  --no-layout-tests --no-doc-comments --use-core --default-enum-style consts \
  -- $inc -D_GNU_SOURCE
sed -i "1i // Generated by tools/bindgen/gen.sh from the PHP $($PHP_CONFIG --version) headers (PHP API $api). Do not edit." "$out"
echo "$out"
